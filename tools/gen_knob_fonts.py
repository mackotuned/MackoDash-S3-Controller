"""Generate the knob's anti-aliased bitmap fonts (main/knob_fonts.c/.h).

usage: gen_knob_fonts.py <font_dir> <out_dir>

<font_dir> must contain the OFL fonts used by the MackoDash V2 theme:
  exo-2_latest_latin-800-italic.ttf, exo-2_latest_latin-900-italic.ttf,
  barlow-semi-condensed_latest_latin-600-normal.ttf,
  barlow-semi-condensed_latest_latin-700-normal.ttf
(from https://fontsource.org: Exo 2 and Barlow Semi Condensed, SIL OFL 1.1).

Glyphs are 4 bpp alpha, ASCII 0x20-0x7E plus the degree sign stored at 0x7F.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 0x20, 0x7F
DEGREE = "°"

FONTS = [
    # c name, ttf file, px, characters
    ("kf_value", "exo-2_latest_latin-900-italic.ttf", 62, "0123456789.-:%/NA" + DEGREE),
    ("kf_value_m", "exo-2_latest_latin-900-italic.ttf", 44, "0123456789.-:%/NA" + DEGREE),
    ("kf_title", "exo-2_latest_latin-800-italic.ttf", 27, "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 -/!?."),
    ("kf_name", "barlow-semi-condensed_latest_latin-700-normal.ttf", 22,
     "".join(chr(c) for c in range(0x20, 0x7F) if not chr(c).islower()) + DEGREE),
    ("kf_label", "barlow-semi-condensed_latest_latin-700-normal.ttf", 16,
     "".join(chr(c) for c in range(0x20, 0x7F) if not chr(c).islower()) + DEGREE),
    ("kf_small", "barlow-semi-condensed_latest_latin-600-normal.ttf", 13,
     "".join(chr(c) for c in range(0x20, 0x7F) if not chr(c).islower()) + DEGREE),
]


def slot(ch: str) -> int:
    return 0x7F if ch == DEGREE else ord(ch)


def render_font(path: str, size: int, chars: str):
    """Returns (line_height, ascent, glyph list, bitmap bytes). Glyph = (offset, w, h, x, y, adv)."""
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    wanted = {slot(c): c for c in chars}
    space_adv = round(font.getlength(" "))
    glyphs, bitmap = [], bytearray()
    for code in range(FIRST, LAST + 1):
        ch = wanted.get(code)
        if ch is None:
            glyphs.append((0, 0, 0, 0, 0, space_adv if code == 0x20 else 0))
            continue
        adv = round(font.getlength(ch))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        offset = len(bitmap)
        if w and h:
            image = Image.new("L", (w, h), 0)
            ImageDraw.Draw(image).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            px = [p >> 4 for p in image.tobytes()]
            if len(px) % 2:
                px.append(0)
            bitmap += bytes((px[i] << 4) | px[i + 1] for i in range(0, len(px), 2))
        else:
            x0 = y0 = 0
        assert 0 <= w < 256 and 0 <= h < 256 and -128 <= x0 < 128 and -128 <= y0 < 128 and adv < 256
        glyphs.append((offset, w, h, x0, y0, adv))
    return ascent + descent, ascent, glyphs, bytes(bitmap)


def load_all(font_dir: str):
    return {name: render_font(os.path.join(font_dir, ttf), px, chars) for name, ttf, px, chars in FONTS}


def write_c(fonts, out_dir: str) -> None:
    header = [
        "/* Generated by tools/gen_knob_fonts.py -- do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    uint32_t offset;   /* into the 4 bpp bitmap, 2 pixels per byte, rows packed */",
        "    uint8_t w, h, adv;",
        "    int8_t x, y;       /* bitmap top-left relative to pen x / baseline */",
        "} kfont_glyph_t;",
        "",
        "typedef struct {",
        "    const uint8_t *bitmap;",
        "    const kfont_glyph_t *glyphs;  /* 0x20..0x7F, 0x7F = degree sign */",
        "    uint8_t line_height, ascent;",
        "} kfont_t;",
        "",
        "#define KFONT_FIRST 0x20",
        "#define KFONT_LAST 0x7F",
        "#define KFONT_DEGREE 0x7F",
        "",
    ]
    source = [
        "/* Generated by tools/gen_knob_fonts.py -- do not edit.",
        " * Exo 2 (c) 2013 The Exo 2 Project Authors; Barlow (c) 2017 The Barlow Project Authors.",
        " * Both licensed under the SIL Open Font License 1.1. */",
        '#include "knob_fonts.h"',
        "",
    ]
    for name, (line_height, ascent, glyphs, bitmap) in fonts.items():
        header.append(f"extern const kfont_t {name};")
        source.append(f"static const uint8_t {name}_bitmap[{max(1, len(bitmap))}] = {{")
        for i in range(0, len(bitmap), 24):
            source.append("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 24]) + ",")
        if not bitmap:
            source.append("    0,")
        source.append("};")
        source.append(f"static const kfont_glyph_t {name}_glyphs[{len(glyphs)}] = {{")
        for code, (offset, w, h, x, y, adv) in zip(range(FIRST, LAST + 1), glyphs):
            source.append(f"    {{{offset}, {w}, {h}, {adv}, {x}, {y}}}, /* 0x{code:02X} */")
        source.append("};")
        source.append(f"const kfont_t {name} = {{{name}_bitmap, {name}_glyphs, {line_height}, {ascent}}};")
        source.append("")
    with open(os.path.join(out_dir, "knob_fonts.h"), "w", newline="\n") as handle:
        handle.write("\n".join(header) + "\n")
    with open(os.path.join(out_dir, "knob_fonts.c"), "w", newline="\n") as handle:
        handle.write("\n".join(source))


if __name__ == "__main__":
    all_fonts = load_all(sys.argv[1])
    write_c(all_fonts, sys.argv[2])
    for font_name, (lh, asc, gl, bm) in all_fonts.items():
        print(f"{font_name}: line {lh}, ascent {asc}, {len(bm)} bytes")
